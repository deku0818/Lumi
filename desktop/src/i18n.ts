const DICT: Record<Lang, Dict> = { zh: ZH, en: EN }

function initialLang(): Lang {
  const saved = localStorage.getItem(KEY)
  if (saved === 'zh' || saved === 'en') return saved
  // 首次：跟随系统语言，中文环境用中文，否则英文
  return navigator.language?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string

type I18nCtx = { lang: Lang; setLang: (l: Lang) => void; t: Translate }
const Ctx = createContext<I18nCtx | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(initialLang)

  const t: Translate = (key, vars) => {
    let s = DICT[lang][key] ?? DICT.en[key] ?? key
    if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, String(vars[k]))
    return s
  }

  useEffect(() => {
    localStorage.setItem(KEY, lang)
    document.documentElement.lang = lang
    // 原生右键菜单由主进程构建，文案在这边翻好推过去
    void window.lumi.setMenuLabels?.({
      undo: t('menu.undo'),
      redo: t('menu.redo'),
      cut: t('menu.cut'),
      copy: t('common.copy'),
      paste: t('menu.paste'),
      selectAll: t('menu.selectAll'),
      copyLink: t('menu.copyLink'),
    })
  }, [lang])

  return createElement(Ctx.Provider, { value: { lang, setLang, t } }, children)
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n 必须在 I18nProvider 内使用')
  return ctx
}
